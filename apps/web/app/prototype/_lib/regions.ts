function toRegion(prefix: string, [label, lat, lng]: [string, number, number]): Region {
  return { id: `${prefix}-${label}`, label, lat, lng };
}

export const REGIONS: Region[] = [
  ...SEOUL.map((r) => toRegion("seoul", r)),
  ...GYEONGGI.map((r) => toRegion("gg", r)),
];

/** 지역명 부분일치 필터(간단 검색). */
export function searchRegions(query: string): Region[] {
  const q = query.trim();
  if (!q) return REGIONS;
  return REGIONS.filter((r) => r.label.includes(q));
}

// 하버사인 거리(km) — 정렬 비교용이라 절대값 정확도는 필요 없다.
function distanceKm(a: Region, b: Region): number {
  const R = 6371;
  const dLat = ((b.lat - a.lat) * Math.PI) / 180;
  const dLng = ((b.lng - a.lng) * Math.PI) / 180;
  const lat1 = (a.lat * Math.PI) / 180;
  const lat2 = (b.lat * Math.PI) / 180;
  const h =
    Math.sin(dLat / 2) ** 2 + Math.sin(dLng / 2) ** 2 * Math.cos(lat1) * Math.cos(lat2);
  return 2 * R * Math.asin(Math.sqrt(h));
}

/**
 * 앵커 지역(현재 위치)에서 가까운 순으로 정렬한 목록.
 * 앵커 자신이 맨 앞(거리 0)에 온다. 앵커를 못 찾으면 원본 순서 유지.
 * "지금 있는 동네" 섹션에서 사용 — 검색 입력과는 별개 경로.
 */
export function regionsByProximity(anchorLabel: string): Region[] {
  const anchor = REGIONS.find((r) => r.label === anchorLabel);
  if (!anchor) return REGIONS;
  return [...REGIONS].sort((a, b) => distanceKm(anchor, a) - distanceKm(anchor, b));
}
